#!/bin/sh
# Regenerate requirements.txt and requirements-dev.txt from pyproject.toml.
#
# Run from the project root after changing dependencies in pyproject.toml:
#   scripts/update-requirements.sh
#
# Needs uv (https://docs.astral.sh/uv/). The output is "universal": one file
# carries environment markers, so it installs on Python 3.11+ on Linux and macOS.
set -eu
cd "$(dirname "$0")/.."

NAME="janus-control-plane"
EXTRAS="--extra server --extra redis --extra postgres"

write() {  # write <file> <description> <extra uv args>
  tmp="$1.tmp"
  # shellcheck disable=SC2086
  uv pip compile pyproject.toml $EXTRAS $3 --universal --python-version 3.11 \
    --no-header --quiet -o "$tmp"
  {
    echo "# Pinned $2 for $NAME."
    echo "#"
    echo "#   python -m venv .venv && . .venv/bin/activate"
    echo "#   pip install -r $1"
    echo "#"
    echo "# The last line installs this project itself (editable), so one command gives"
    echo "# a working install. Run it from the project root. Generated by"
    echo "# scripts/update-requirements.sh from pyproject.toml — do not edit by hand."
    echo
    cat "$tmp"
    echo
    echo "-e ."
  } > "$1"
  rm -f "$tmp"
}

write requirements.txt "runtime dependencies" ""
write requirements-dev.txt "runtime + development dependencies (tests, lint)" "--extra dev"
echo "wrote requirements.txt and requirements-dev.txt"
